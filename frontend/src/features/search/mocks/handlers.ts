import { delay, type HttpHandler } from 'msw';
import type { TicketSearchResult } from '@/shared/api';
import { getSearchTicketsMockHandler } from '@/shared/api/generated/search/search.msw';
import { MOCK_DELAY_MS } from '@/shared/api/mocks';
import { MOCK_SEARCH_RESULTS, type MockSearchResult } from './search-data';

/** Query (title or Solution text, any case), Department, source and Resolved days (spec AC-004.3). */
function matching(url: URL): MockSearchResult[] {
  const params = url.searchParams;
  const q = params.get('q')?.trim().toLowerCase() ?? '';
  const departmentId = params.get('departmentId');
  const source = params.get('source');
  const from = params.get('resolvedFrom');
  const to = params.get('resolvedTo');
  return MOCK_SEARCH_RESULTS.filter((t) => {
    const day = t.resolvedAt.slice(0, 10); // same day in Vietnam time (search-data.ts)
    return (
      [t.title, t.excerpt, t.solution].some((text) => text.toLowerCase().includes(q)) &&
      (!departmentId || t.department.departmentId === departmentId) &&
      (!source || t.source === source) &&
      (!from || day >= from) &&
      (!to || day <= to)
    );
  });
}

/** The API result without the source and Solution text. */
function toResult({
  source: _source,
  solution: _solution,
  ...result
}: MockSearchResult): TicketSearchResult {
  return result;
}

/**
 * MSW mock handlers of the "search" feature (guideline 10 §5). Hand-written handlers with realistic data go here;
 * endpoints without one fall back to orval's generated fake-data handlers (src/mocks/handlers.ts).
 */
export const handlers: HttpHandler[] = [
  // Typed handler generated by orval: the resolver must return a TicketSearchResultPage.
  getSearchTicketsMockHandler(async ({ request }) => {
    await delay(MOCK_DELAY_MS);
    const url = new URL(request.url);
    const size = Number(url.searchParams.get('size')) || 20;
    const page = Number(url.searchParams.get('page')) || 0;
    const all = matching(url);
    return {
      content: all.slice(page * size, page * size + size).map(toResult),
      page: {
        size,
        number: page,
        totalElements: all.length,
        totalPages: Math.ceil(all.length / size),
      },
    };
  }),
];

/** Restores this feature's mock data to its starting state — called after every test (src/test/setup.ts). */
export function resetMockData(): void {
  // The mock results never change: the search only reads them.
}
