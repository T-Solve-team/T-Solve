import { delay, type HttpHandler } from 'msw';
import type { TicketSummary } from '@/shared/api';
import { getGetTicketsMockHandler } from '@/shared/api/generated/tickets/tickets.msw';
import { MOCK_DELAY_MS } from '@/shared/api/mocks';
import { parseSort } from '@/shared/lib';
import { MOCK_TICKETS, type MockTicket } from './ticket-data';

/** Sort keys of the Ticket List (spec AC-001.8); missing values sort first. */
const SORT_VALUE: Record<string, (t: MockTicket) => string> = {
  sourceTicketId: (t) => t.sourceTicketId,
  title: (t) => t.title,
  project: (t) => t.project.name,
  reviewDueDate: (t) => t.reviewDueDate ?? '',
  updatedAt: (t) => t.updatedAt,
};

/** Keyword (Ticket ID, title or Solution, any case), Department, source and status (spec AC-004.2). */
function filtered(url: URL): MockTicket[] {
  const params = url.searchParams;
  const keyword = params.get('keyword')?.trim().toLowerCase();
  const departmentId = params.get('departmentId');
  const source = params.get('source');
  const status = params.get('status');
  return MOCK_TICKETS.filter(
    (t) =>
      (!keyword ||
        [t.sourceTicketId, t.title, t.solution].some((text) =>
          text.toLowerCase().includes(keyword),
        )) &&
      (!departmentId || t.department.departmentId === departmentId) &&
      (!source || t.source === source) &&
      (!status || t.status === status),
  );
}

function sorted(tickets: MockTicket[], url: URL): MockTicket[] {
  const sort = parseSort(url.searchParams.get('sort')) ?? { field: 'updatedAt', order: 'desc' };
  const value = SORT_VALUE[sort.field] ?? SORT_VALUE.updatedAt;
  const direction = sort.order === 'asc' ? 1 : -1;
  return [...tickets].sort(
    (a, b) =>
      (value ? value(a).localeCompare(value(b)) : 0) * direction ||
      a.ticketId.localeCompare(b.ticketId),
  );
}

/** The API row without the Solution text. */
function toSummary({ solution: _solution, ...summary }: MockTicket): TicketSummary {
  return summary;
}

/**
 * MSW mock handlers of the "tickets" feature (guideline 10 §5). Hand-written handlers with realistic data go here;
 * endpoints without one fall back to orval's generated fake-data handlers (src/mocks/handlers.ts).
 */
export const handlers: HttpHandler[] = [
  // Typed handler generated by orval: the resolver must return a TicketSummaryPage.
  getGetTicketsMockHandler(async ({ request }) => {
    await delay(MOCK_DELAY_MS);
    const url = new URL(request.url);
    const size = Number(url.searchParams.get('size')) || 20;
    const page = Number(url.searchParams.get('page')) || 0;
    const all = sorted(filtered(url), url);
    return {
      content: all.slice(page * size, page * size + size).map(toSummary),
      page: {
        size,
        number: page,
        totalElements: all.length,
        totalPages: Math.ceil(all.length / size),
      },
    };
  }),
];

/** Restores this feature's mock data to its starting state — called after every test (src/test/setup.ts). */
export function resetMockData(): void {
  // The mock tickets never change: the Ticket List only reads them.
}
